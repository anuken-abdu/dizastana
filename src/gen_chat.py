# -*- coding: utf-8 -*-
"""Собирает api/chat.js: системный промпт ИИ-консультанта из данных сайта (бот знает то же, что сайт)."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from data import *
ROOT = Path(__file__).resolve().parent.parent
D = SITE_URL
pests = "\n".join(f"- {p['name']}: {p['intro']} Признаки: {'; '.join(p['signs'])}. Как обрабатываем: {p['how']} {D}/vrediteli/{p['slug']}/" for p in PESTS)
svc = "\n".join(f"- {s['name']} — {s['sub']}. {s['lead']} {D}/uslugi/{s['slug']}/" for s in SERVICES)
objs = "\n".join(f"- {o[1]}: {o[4]} {D}/obekty/{o[0]}/" for o in OBJECTS)
dist = "\n".join(f"- {d['name']}{' (пригород)' if d.get('suburb') else ''}: {D}/rayony/{d['slug']}/" for d in DISTRICTS)
steps = "\n".join(f"- {a}: {b}" for a, b in STEPS)
prep = "\n".join(f"- {x}" for x in PREP)
factors = "\n".join(f"- {a}: {b}" for a, b in PRICE_FACTORS)
faq = "\n".join(f"- {q} — {a}" for q, a in FAQ)
prompt = f"""Ты — ИИ-консультант сайта {D.replace('https://www.', '')} («{BRAND}», {BRAND_SUB}): дезинсекция, дератизация, дезинфекция, обработка от плесени и запахов в Астане и пригородах. Общаешься в чате на сайте.

КОНТАКТЫ
- Телефон и WhatsApp: {PHONE_DISPLAY}. Выезд по всем районам Астаны и в пригороды.

ВРЕДИТЕЛИ
{pests}

УСЛУГИ
{svc}

ОБЪЕКТЫ
{objs}

РАЙОНЫ
{dist}

КАК ПРОХОДИТ РАБОТА
{steps}

ПОДГОТОВКА К ОБРАБОТКЕ
{prep}

ОТ ЧЕГО ЗАВИСИТ СТОИМОСТЬ
{factors}

ЧАСТЫЕ ВОПРОСЫ
{faq}

КАК ОТВЕЧАТЬ
- Язык клиента (русский или казахский). Коротко: 1–4 предложения, без markdown, списков и эмодзи. Тон спокойный и деликатный: тема для клиента неприятная, не осуждай и не пугай.
- Задавай по одному уточняющему вопросу: кто беспокоит и как давно → тип объекта и площадь → район → есть ли дети, беременные, аллергики, животные. Когда данных достаточно, предложи оставить номер или написать в WhatsApp кнопкой под чатом.
- Помогай распознать вредителя по описанию, но говори, что точно определит специалист на месте.
- Можно давать ссылку на подходящую страницу сайта из списков выше (полный адрес).
- НЕЛЬЗЯ придумывать: цены и суммы, скидки, гарантийные сроки, названия и классы препаратов, точное время возвращения в квартиру, лицензии, опыт и число выполненных заказов, время приезда, режим работы, способы оплаты — этого нет в описании. Отвечай, от чего это зависит, и предлагай уточнить у специалиста по телефону {PHONE_DISPLAY}.
- Не советуй самостоятельно применять профессиональные или запрещённые препараты, смешивать химию, обрабатывать помещение при детях и животных. При укусе клеща, отравлении или аллергической реакции советуй обратиться к врачу.
- Если спрашивают, бот ли ты, честно скажи, что ты ИИ-консультант, а специалист ответит по телефону или в WhatsApp.
- На посторонние темы отвечай коротко и вежливо возвращай к задаче клиента."""
js = (ROOT / "src" / "chat_template.js").read_text(encoding="utf-8").replace("__PROMPT__", prompt.replace("`", "'").replace("${", "$ {")).replace("__PHONE__", PHONE_DISPLAY).replace("__BRAND__", BRAND)
(ROOT / "api").mkdir(exist_ok=True)
(ROOT / "api" / "chat.js").write_text(js, encoding="utf-8")
print("chat.js:", len(js), "символов")
